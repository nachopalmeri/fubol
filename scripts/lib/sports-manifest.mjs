import fs from 'node:fs';
import path from 'node:path';

export function validateSportsManifest(value) {
  let url;
  try { url = new URL(value); } catch { throw new Error('Invalid Sports Streams manifest URL'); }
  if (url.protocol !== 'https:' || url.hostname !== 'sports.highfly.to' || !url.pathname.endsWith('/manifest.json') || url.username || url.password) {
    throw new Error('Use the Sports Streams HTTPS manifest generated by its normal configure flow');
  }
  try {
    const parts = url.pathname.split('/').filter(Boolean);
    const config = JSON.parse(Buffer.from(parts.at(-2) ?? '', 'base64url').toString('utf8'));
    if (typeof config.freeUserId !== 'string' || !config.freeUserId.trim() || config.freeUserId.length > 256) throw new Error();
  } catch {
    throw new Error('Complete the provider verification and use its generated personal manifest, not the public template URL');
  }
  return url;
}

export function applySportsManifest(config, root) {
  const file = path.join(root, '.secrets', 'sports-manifest.txt');
  if (!fs.existsSync(file)) return false;
  const value = fs.readFileSync(file, 'utf8').trim();
  validateSportsManifest(value);
  const preset = config.presets?.find((item) => item.instanceId === 'sports-streams');
  if (!preset) return false;
  preset.options.manifestUrl = value;
  return true;
}
