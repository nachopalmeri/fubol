#!/usr/bin/env node
/**
 * Prepare, activate and inspect the AIOStreams user configuration.
 *
 * The TorBox API key is read from .secrets/torbox.key and is never printed.
 * The AIOStreams user password is generated once, stored in
 * .secrets/aiostreams-user.env and never printed either.
 *
 * Usage:
 *   node scripts/aiostreams-config.mjs prepare          # create/update with placeholder or current key
 *   node scripts/aiostreams-config.mjs prepare --require-key
 *   node scripts/aiostreams-config.mjs status
 *   node scripts/aiostreams-config.mjs delete --yes     # destructive: only for a throwaway config
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {
  applyTorboxMode,
  TORBOX_PLACEHOLDER as PLACEHOLDER,
} from './lib/torbox-mode.mjs';

const ROOT = process.cwd();
const ENV_PATH = path.join(ROOT, '.env');
const SECRETS_DIR = path.join(ROOT, '.secrets');
const KEY_PATH = path.join(SECRETS_DIR, 'torbox.key');
const USER_ENV_PATH = path.join(SECRETS_DIR, 'aiostreams-user.env');
const CONFIG_PATH = path.join(ROOT, 'config', 'aiostreams', 'fubol.config.json');
const LOCAL_BASE = 'http://127.0.0.1:3000';

function fail(message, code = 1) {
  console.error(`ERROR: ${message}`);
  process.exit(code);
}

function log(message) {
  console.log(message);
}

function parseEnvFile(file) {
  const result = {};
  if (!fs.existsSync(file)) return result;
  for (const raw of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq < 1) continue;
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    result[line.slice(0, eq).trim()] = value;
  }
  return result;
}

function basicAuth(uuid, password) {
  return `Basic ${Buffer.from(`${uuid}:${password}`, 'utf8').toString('base64')}`;
}

function readKey() {
  if (!fs.existsSync(KEY_PATH)) return null;
  const key = fs.readFileSync(KEY_PATH, 'utf8').trim();
  if (!key) return null;
  if (/\s/.test(key)) fail('torbox.key must contain a single line with no spaces');
  return key;
}

function readStoredUser() {
  const env = parseEnvFile(USER_ENV_PATH);
  return {
    uuid: env.AIOSTREAMS_UUID || '',
    password: env.AIOSTREAMS_PASSWORD || '',
    encryptedPassword: env.AIOSTREAMS_ENCRYPTED_PASSWORD || '',
    manifestUrl: env.AIOSTREAMS_MANIFEST_URL || '',
    manifestUrlLocal: env.AIOSTREAMS_MANIFEST_URL_LOCAL || '',
  };
}

function writeStoredUser(data) {
  fs.mkdirSync(SECRETS_DIR, { recursive: true });
  const lines = [
    '# Generated by scripts/aiostreams-config.mjs. Do not commit.',
    `AIOSTREAMS_UUID=${data.uuid}`,
    `AIOSTREAMS_PASSWORD=${data.password}`,
    `AIOSTREAMS_ENCRYPTED_PASSWORD=${data.encryptedPassword}`,
    `AIOSTREAMS_MANIFEST_URL=${data.manifestUrl}`,
    `AIOSTREAMS_MANIFEST_URL_LOCAL=${data.manifestUrlLocal}`,
    '',
  ];
  fs.writeFileSync(USER_ENV_PATH, lines.join('\n'), {
    encoding: 'utf8',
    mode: 0o600,
  });
}

function manifestUrls(uuid, encryptedPassword, serverHost) {
  const host = serverHost.replace(/^https?:\/\//, '').replace(/\/+$/, '');
  const suffix = `/stremio/${uuid}/${encryptedPassword}/manifest.json`;
  return {
    manifestUrl: `https://${host}${suffix}`,
    manifestUrlLocal: `${LOCAL_BASE}${suffix}`,
  };
}

function getCookie(response) {
  const raw =
    typeof response.headers.getSetCookie === 'function'
      ? response.headers.getSetCookie()
      : [response.headers.get('set-cookie')].filter(Boolean);
  for (const cookie of raw) {
    const match = /(?:^|,\s*)(aiostreams\.session=[^;]+)/.exec(cookie);
    if (match) return match[1];
  }
  return null;
}

async function readJson(response) {
  const text = await response.text();
  if (!text) return null;
  try {
    return JSON.parse(text);
  } catch {
    return null;
  }
}

function safeError(body) {
  const code = body?.error?.code;
  const message = body?.error?.message;
  if (!code && !message) return '';
  return ` (${[code, message].filter(Boolean).join(': ')})`;
}

async function login(base, authValue) {
  const colon = authValue.indexOf(':');
  if (colon < 1) fail('AIOSTREAMS_AUTH must use the form user:password');
  const username = authValue.slice(0, colon);
  const password = authValue.slice(colon + 1);
  const response = await fetch(`${base}/api/v1/auth/login`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ username, password }),
  });
  const body = await readJson(response);
  if (response.status !== 200) {
    fail(`AIOStreams login failed (HTTP ${response.status})${safeError(body)}`);
  }
  const cookie = getCookie(response);
  if (!cookie) fail('AIOStreams login succeeded but no session cookie was returned');
  return cookie;
}

async function loadConfig(key) {
  if (!fs.existsSync(CONFIG_PATH)) fail(`missing config template: ${CONFIG_PATH}`);
  let config;
  try {
    config = JSON.parse(fs.readFileSync(CONFIG_PATH, 'utf8'));
  } catch (error) {
    fail(`config template is not valid JSON: ${error.message}`);
  }
  try {
    applyTorboxMode(config, key);
  } catch (error) {
    fail(error.message);
  }
  return config;
}

async function fetchManifest(manifestUrl) {
  const response = await fetch(manifestUrl, {
    headers: { accept: 'application/json' },
  });
  const body = await readJson(response);
  return { response, body };
}

function printManifest(manifestUrl, label) {
  return fetchManifest(manifestUrl).then(({ response, body }) => {
    log(`${label}_http=${response.status}`);
    if (response.status !== 200 || !body) return;
    log(`${label}_name=${body.name || 'unknown'}`);
    log(`${label}_resources=${(body.resources || []).join(',')}`);
    log(`${label}_types=${(body.types || []).join(',')}`);
    log(`${label}_catalogs=${(body.catalogs || []).length}`);
  });
}

async function prepare(requireKey) {
  const env = parseEnvFile(ENV_PATH);
  const auth = env.AIOSTREAMS_AUTH;
  const serverHost = env.SERVER_HOST;
  if (!auth) fail('AIOSTREAMS_AUTH is missing from .env');
  if (!serverHost) fail('SERVER_HOST is missing from .env');

  const key = readKey();
  if (requireKey && !key) {
    fail('torbox.key is missing or empty; create .secrets/torbox.key first');
  }

  const config = await loadConfig(key);
  const cookie = await login(LOCAL_BASE, auth);
  const stored = readStoredUser();
  let uuid;
  let password;
  let encryptedPassword;

  if (stored.uuid && stored.password) {
    const authHeader = basicAuth(stored.uuid, stored.password);
    const check = await fetch(`${LOCAL_BASE}/api/v1/user`, {
      headers: { authorization: authHeader },
    });
    const checkBody = await readJson(check);
    if (check.status !== 200) {
      fail(
        `existing AIOStreams user is not accessible (HTTP ${check.status})${safeError(checkBody)}; refusing to overwrite`
      );
    }
    encryptedPassword =
      checkBody?.data?.encryptedPassword || stored.encryptedPassword;
    if (!encryptedPassword) fail('could not read encryptedPassword for the existing user');

    const update = await fetch(`${LOCAL_BASE}/api/v1/user`, {
      method: 'PUT',
      headers: {
        authorization: authHeader,
        cookie,
        'content-type': 'application/json',
      },
      body: JSON.stringify({ config }),
    });
    const updateBody = await readJson(update);
    if (update.status !== 200) {
      fail(`config update failed (HTTP ${update.status})${safeError(updateBody)}`);
    }
    uuid = stored.uuid;
    password = stored.password;
    log('config=updated');
  } else {
    password = crypto.randomBytes(24).toString('hex');
    const create = await fetch(`${LOCAL_BASE}/api/v1/user`, {
      method: 'POST',
      headers: { cookie, 'content-type': 'application/json' },
      body: JSON.stringify({ config, password }),
    });
    const createBody = await readJson(create);
    if (create.status !== 201) {
      fail(`config creation failed (HTTP ${create.status})${safeError(createBody)}`);
    }
    uuid = createBody?.data?.uuid;
    encryptedPassword = createBody?.data?.encryptedPassword;
    if (!uuid || !encryptedPassword) {
      fail('config creation returned no uuid/encryptedPassword');
    }
    log('config=created');
  }

  const urls = manifestUrls(uuid, encryptedPassword, serverHost);
  writeStoredUser({
    uuid,
    password,
    encryptedPassword,
    manifestUrl: urls.manifestUrl,
    manifestUrlLocal: urls.manifestUrlLocal,
  });

  log(`torbox_key=${key ? 'present' : 'pending'}`);
  log('aiostreams_credentials=saved');
  log('manifest_url=saved');
  await printManifest(urls.manifestUrlLocal, 'manifest');
}

async function status() {
  const env = parseEnvFile(ENV_PATH);
  const auth = env.AIOSTREAMS_AUTH;
  if (!auth) fail('AIOSTREAMS_AUTH is missing from .env');
  const stored = readStoredUser();
  log(`key_present=${readKey() ? 'true' : 'false'}`);
  log(`stored=${stored.uuid && stored.password ? 'true' : 'false'}`);
  if (!stored.uuid || !stored.password) return;

  const authHeader = basicAuth(stored.uuid, stored.password);
  const response = await fetch(`${LOCAL_BASE}/api/v1/user`, {
    headers: { authorization: authHeader },
  });
  const body = await readJson(response);
  log(`config_http=${response.status}`);
  if (response.status !== 200) return;
  const user = body?.data?.userData;
  log(`addon_name=${user?.addonName || 'unknown'}`);
  log(`presets=${Array.isArray(user?.presets) ? user.presets.length : 0}`);
  log(
    `services=${(user?.services || []).map((s) => s.id).filter(Boolean).join(',') || 'none'}`
  );
  const torboxConfigured = (user?.services || []).some(
    (s) => s.id === 'torbox' && s.credentials?.apiKey !== PLACEHOLDER
  );
  log(`torbox_configured=${torboxConfigured}`);
  log(`vod_mode=${torboxConfigured ? 'debrid' : 'p2p'}`);
  if (stored.manifestUrlLocal) {
    await printManifest(stored.manifestUrlLocal, 'manifest');
  }
}

async function remove(confirmed) {
  if (!confirmed) fail('delete requires --yes');
  const stored = readStoredUser();
  if (!stored.uuid || !stored.password) fail('no stored user to delete');
  const response = await fetch(`${LOCAL_BASE}/api/v1/user`, {
    method: 'DELETE',
    headers: { authorization: basicAuth(stored.uuid, stored.password) },
  });
  const body = await readJson(response);
  if (response.status !== 200) {
    fail(`config delete failed (HTTP ${response.status})${safeError(body)}`);
  }
  log('config=deleted');
}

const action = process.argv[2] || 'prepare';
const args = new Set(process.argv.slice(3));

if (action === 'prepare') {
  await prepare(args.has('--require-key'));
} else if (action === 'status') {
  await status();
} else if (action === 'delete') {
  await remove(args.has('--yes'));
} else {
  fail(`unknown action: ${action}`);
}
